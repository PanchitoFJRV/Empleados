DROP TABLE EMPLEADOS;
DROP SEQUENCE EMPLEADOS_GENERADOR_PK;

CREATE TABLE EMPLEADOS (
ID_EMPLEADO INT PRIMARY KEY,
NSS VARCHAR(15) NOT NULL UNIQUE,
NOMBRE VARCHAR(50) NOT NULL,
APELLIDO_PATERNO VARCHAR(50) NOT NULL,
APELLIDO_MATERNO VARCHAR(50) NOT NULL,
SUELDO NUMBER(10,2) CHECK(SUELDO >0));

CREATE SEQUENCE EMPLEADOS_GENERADOR_PK
START WITH 1
INCREMENT BY 1;

CREATE OR REPLACE TRIGGER EMPLEADOS_PK_AGREGAR
BEFORE INSERT
ON EMPLEADOS
FOR EACH ROW 
BEGIN
 SELECT EMPLEADOS_GENERADOR_PK.NEXTVAL
    INTO :NEW.ID_EMPLEADO
    FROM DUAL;
END;
/

